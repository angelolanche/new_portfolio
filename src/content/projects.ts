export type Project = (typeof projects)[number];
export function signalVideoFor(project: Project) {
  const video =
    project.videos[
      'signalVideoIndex' in project ? project.signalVideoIndex : 0
    ];
  if (!video) throw new Error(`No signal video for ${project.slug}`);
  return video;
}
export function projectFromPath(path: string) {
  const normalizedPath = path.replace(/\/+$/, '');
  return projects.find(
    (project) => normalizedPath === '/projects/' + project.slug,
  );
}
